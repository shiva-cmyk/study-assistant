/**
 * Validates and sanitizes the structured study set generated by the AI model or demo generator.
 */
function validateAndSanitizeStudySet(data, expectedConfig = {}) {
  const errors = [];

  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    return { valid: false, errors: ['Response must be a JSON object'] };
  }

  // 1. Validate title
  if (!data.title || typeof data.title !== 'string' || data.title.trim().length === 0) {
    errors.push('Field "title" must be a non-empty string');
  }

  // 2. Validate summary
  const summary = typeof data.summary === 'string' && data.summary.trim().length > 0
    ? data.summary.trim()
    : 'Comprehensive study set covering key concepts, mechanisms, and practice questions.';

  // 3. Validate metadata
  const metadata = {
    difficulty: ['beginner', 'intermediate', 'advanced'].includes(data.metadata?.difficulty?.toLowerCase())
      ? data.metadata.difficulty.toLowerCase()
      : (expectedConfig.difficulty || 'intermediate'),
    mode: ['balanced', 'concept', 'exam'].includes(data.metadata?.mode?.toLowerCase())
      ? data.metadata.mode.toLowerCase()
      : (expectedConfig.mode || 'balanced'),
    estimatedMinutes: typeof data.metadata?.estimatedMinutes === 'number' && data.metadata.estimatedMinutes > 0
      ? Math.min(Math.max(data.metadata.estimatedMinutes, 5), 60)
      : Math.max(Math.round(((data.cards?.length || 8) * 1.5) + ((data.quiz?.length || 5) * 1.2)), 5),
    topics: Array.isArray(data.metadata?.topics) && data.metadata.topics.length > 0
      ? data.metadata.topics.filter(t => typeof t === 'string' && t.trim().length > 0).map(t => t.trim())
      : ['Core Principles', 'Key Distinctions', 'Practical Application'],
  };

  // 4. Validate cards
  if (!Array.isArray(data.cards) || data.cards.length === 0) {
    errors.push('Field "cards" must be a non-empty array of flashcard objects');
  } else {
    const cardQuestions = new Set();
    data.cards.forEach((card, index) => {
      if (!card || typeof card !== 'object') {
        errors.push(`Card at index ${index} must be an object`);
        return;
      }
      if (!card.question || typeof card.question !== 'string' || card.question.trim().length === 0) {
        errors.push(`Card ${index + 1} is missing a valid "question" string`);
      } else {
        const qNorm = card.question.trim().toLowerCase();
        if (cardQuestions.has(qNorm)) {
          errors.push(`Card ${index + 1} is a duplicate of another card question`);
        }
        cardQuestions.add(qNorm);
      }
      if (!card.answer || typeof card.answer !== 'string' || card.answer.trim().length === 0) {
        errors.push(`Card ${index + 1} is missing a valid "answer" string`);
      } else if (card.question && card.question.trim().toLowerCase() === card.answer.trim().toLowerCase()) {
        errors.push(`Card ${index + 1} question and answer cannot be identical`);
      }
    });
  }

  // 5. Validate quiz
  if (!Array.isArray(data.quiz) || data.quiz.length === 0) {
    errors.push('Field "quiz" must be a non-empty array of quiz question objects');
  } else {
    const quizQuestions = new Set();
    data.quiz.forEach((q, index) => {
      if (!q || typeof q !== 'object') {
        errors.push(`Quiz item at index ${index} must be an object`);
        return;
      }
      if (!q.question || typeof q.question !== 'string' || q.question.trim().length === 0) {
        errors.push(`Quiz question ${index + 1} is missing a valid "question" string`);
      } else {
        const qNorm = q.question.trim().toLowerCase();
        if (quizQuestions.has(qNorm)) {
          errors.push(`Quiz question ${index + 1} is a duplicate of another quiz question`);
        }
        quizQuestions.add(qNorm);
      }
      if (!Array.isArray(q.options) || q.options.length !== 4) {
        errors.push(`Quiz question ${index + 1} must have an "options" array with exactly 4 choices`);
      } else {
        const hasInvalidOption = q.options.some((opt) => typeof opt !== 'string' || opt.trim().length === 0);
        if (hasInvalidOption) {
          errors.push(`Quiz question ${index + 1} contains empty or non-string options`);
        }
        const uniqueOptions = new Set(q.options.map(o => typeof o === 'string' ? o.trim().toLowerCase() : ''));
        if (uniqueOptions.size < 3) {
          errors.push(`Quiz question ${index + 1} options must be distinct`);
        }
      }
      if (
        typeof q.answer !== 'number' ||
        !Number.isInteger(q.answer) ||
        q.answer < 0 ||
        q.answer > 3
      ) {
        errors.push(`Quiz question ${index + 1} "answer" must be an integer between 0 and 3`);
      }
      if (!q.explanation || typeof q.explanation !== 'string' || q.explanation.trim().length === 0) {
        errors.push(`Quiz question ${index + 1} is missing a valid "explanation" string`);
      }
    });
  }

  if (errors.length > 0) {
    return { valid: false, errors };
  }

  const sanitizedData = {
    title: data.title.trim(),
    summary,
    metadata,
    cards: data.cards.map((c, i) => ({
      id: `card-${i + 1}`,
      category: typeof c.category === 'string' && c.category.trim() ? c.category.trim() : 'Core Concept',
      question: c.question.trim(),
      answer: c.answer.trim(),
      difficulty: ['easy', 'medium', 'hard'].includes(c.difficulty?.toLowerCase())
        ? c.difficulty.toLowerCase()
        : metadata.difficulty === 'beginner' ? 'easy' : metadata.difficulty === 'advanced' ? 'hard' : 'medium',
    })),
    quiz: data.quiz.map((q, i) => ({
      id: `quiz-${i + 1}`,
      category: typeof q.category === 'string' && q.category.trim() ? q.category.trim() : 'Concept Check',
      question: q.question.trim(),
      options: q.options.map((opt) => opt.trim()),
      answer: q.answer,
      explanation: q.explanation.trim(),
      difficulty: ['easy', 'medium', 'hard'].includes(q.difficulty?.toLowerCase())
        ? q.difficulty.toLowerCase()
        : metadata.difficulty === 'beginner' ? 'easy' : metadata.difficulty === 'advanced' ? 'hard' : 'medium',
    })),
  };

  return { valid: true, errors: [], sanitizedData };
}

/**
 * Strips accidental markdown code blocks (```json ... ```) or whitespace
 */
function cleanRawJsonResponse(raw) {
  let cleaned = raw.trim();
  if (cleaned.startsWith('```json')) {
    cleaned = cleaned.replace(/^```json\s*/i, '').replace(/\s*```$/, '');
  } else if (cleaned.startsWith('```')) {
    cleaned = cleaned.replace(/^```\s*/, '').replace(/\s*```$/, '');
  }
  return cleaned.trim();
}

/**
 * Attempts Gemini LLM generation with automatic model fallback
 */
async function callGeminiWithFallback(apiKey, systemInstruction, userPrompt) {
  const genAI = new GoogleGenerativeAI(apiKey);
  const candidateModels = [
    'gemini-3.5-flash-lite',
    'gemini-3.8-flash'
  ];
  let lastError = null;
  for (const modelName of candidateModels) {
    try {
      const model = genAI.getGenerativeModel({
        model: modelName,
        generationConfig: {
          responseMimeType: 'application/json',
          temperature: 0.2,
        },
      });

      const result = await model.generateContent([
        { text: systemInstruction },
        { text: userPrompt },
      ]);

      const text = result.response.text();
      if (text && text.trim().length > 0) {
        return text;
      }
    } catch (err) {
      lastError = err;
      console.warn(`[StudyFlow Backend] Model ${modelName} call failed:`, err.message);
    }
  }

  throw lastError || new Error('All candidate Gemini models failed to generate content.');
}

