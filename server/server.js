/**
 * Socket.IO Real-Time Event Handlers
 */
io.on('connection', (socket) => {
  console.log(`[Socket.IO] Client connected: ${socket.id}`);

  // 1. Room Creation
  socket.on('room:create', (payload, callback) => {
    try {
      const room = roomManager.createRoom(payload || {}, socket);
      const roomState = roomManager.getSerializableRoomState(room.id);
      if (typeof callback === 'function') {
        callback({ success: true, roomId: room.id, roomState });
      }
      socket.emit('room:state-update', roomState);
    } catch (err) {
      console.error('[Socket.IO] Error creating room:', err);
      if (typeof callback === 'function') {
        callback({ success: false, error: 'Failed to create study room.' });
      }
    }
  });

  // 2. Room Joining
  socket.on('room:join', ({ roomId, userName }, callback) => {
    try {
      const result = roomManager.joinRoom(roomId, userName, socket);
      if (!result.success) {
        if (typeof callback === 'function') callback({ success: false, error: result.error });
        return;
      }

      const roomState = roomManager.getSerializableRoomState(result.room.id);
      if (typeof callback === 'function') {
        callback({
          success: true,
          roomId: result.room.id,
          participant: result.participant,
          roomState,
        });
      }

      // Notify other peers in room
      socket.to(result.room.id).emit('room:participant-joined', {
        participant: result.participant,
        roomState,
      });

      if (result.joinMsg) {
        io.to(result.room.id).emit('chat:message', result.joinMsg);
      }

      io.to(result.room.id).emit('room:state-update', roomState);
    } catch (err) {
      console.error('[Socket.IO] Error joining room:', err);
      if (typeof callback === 'function') {
        callback({ success: false, error: 'Could not join room.' });
      }
    }
  });

  // 3. Room Leaving
  socket.on('room:leave', () => {
    handleUserDisconnect(socket);
  });

  socket.on('disconnect', () => {
    console.log(`[Socket.IO] Client disconnected: ${socket.id}`);
    handleUserDisconnect(socket);
  });

  function handleUserDisconnect(s) {
    const leaveResult = roomManager.leaveRoom(s.id);
    if (!leaveResult) return;

    const { roomId, departingId, departingName, newHostId, room, leaveMsg, roomEnded } = leaveResult;

    if (roomEnded) {
      io.to(roomId).emit('room:ended', { message: 'All participants have left the room.' });
      return;
    }

    if (leaveMsg) {
      io.to(roomId).emit('chat:message', leaveMsg);
    }

    const updatedState = roomManager.getSerializableRoomState(roomId);
    io.to(roomId).emit('room:participant-left', {
      participantId: departingId,
      participantName: departingName,
      newHostId,
      roomState: updatedState,
    });
    io.to(roomId).emit('room:state-update', updatedState);
  }

  // 4. WebRTC Mesh Signaling
  socket.on('webrtc:offer', ({ targetId, sdp }) => {
    if (targetId && sdp) {
      io.to(targetId).emit('webrtc:offer', {
        senderId: socket.id,
        sdp,
      });
    }
  });

  socket.on('webrtc:answer', ({ targetId, sdp }) => {
    if (targetId && sdp) {
      io.to(targetId).emit('webrtc:answer', {
        senderId: socket.id,
        sdp,
      });
    }
  });

  socket.on('webrtc:ice-candidate', ({ targetId, candidate }) => {
    if (targetId && candidate) {
      io.to(targetId).emit('webrtc:ice-candidate', {
        senderId: socket.id,
        candidate,
      });
    }
  });

  // Media state broadcast (mic, camera, live speaking detection)
  socket.on('webrtc:media-state', ({ roomId, micEnabled, cameraEnabled, isSpeaking }) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const room = roomManager.rooms.get(cleanRoomId);
    if (room) {
      const p = room.participants.get(socket.id);
      if (p) {
        if (typeof micEnabled === 'boolean') p.micEnabled = micEnabled;
        if (typeof cameraEnabled === 'boolean') p.cameraEnabled = cameraEnabled;
        if (typeof isSpeaking === 'boolean') p.isSpeaking = isSpeaking;
      }
      socket.to(cleanRoomId).emit('webrtc:media-state-updated', {
        participantId: socket.id,
        micEnabled: p?.micEnabled,
        cameraEnabled: p?.cameraEnabled,
        isSpeaking: p?.isSpeaking,
      });
    }
  });

  // 5. Real-Time Chat
  socket.on('chat:send', ({ roomId, message, userName }) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const room = roomManager.rooms.get(cleanRoomId);
    if (!room) return;

    const sanitized = sanitizeMessage(message);
    if (!sanitized) return;

    const chatMsg = {
      id: `chat-${Date.now()}-${socket.id.slice(0, 4)}`,
      roomId: cleanRoomId,
      userId: socket.id,
      userName: userName || room.participants.get(socket.id)?.name || 'Student',
      message: sanitized,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    };

    room.chatMessages.push(chatMsg);
    io.to(cleanRoomId).emit('chat:message', chatMsg);
  });

  // 6. Group Quiz Synchronization
  socket.on('quiz:start', ({ roomId }, callback) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const res = roomManager.startGroupQuiz(cleanRoomId, socket.id);
    if (typeof callback === 'function') callback(res);
    if (res.success) {
      io.to(cleanRoomId).emit('room:state-update', res.roomState);
      if (res.quizStartMsg) io.to(cleanRoomId).emit('chat:message', res.quizStartMsg);
    }
  });

  socket.on('quiz:submit-answer', ({ roomId, optionIndex }, callback) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const res = roomManager.submitQuizAnswer(cleanRoomId, socket.id, optionIndex);
    if (typeof callback === 'function') callback(res);
    if (res.success) {
      io.to(cleanRoomId).emit('room:state-update', res.roomState);
    }
  });

  socket.on('quiz:reveal', ({ roomId }) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const res = roomManager.revealQuizQuestion(cleanRoomId, socket.id);
    if (res.success) {
      io.to(cleanRoomId).emit('room:state-update', res.roomState);
    }
  });

  socket.on('quiz:next', ({ roomId }, callback) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const res = roomManager.nextQuizQuestion(cleanRoomId, socket.id);
    if (typeof callback === 'function') callback(res);
    if (res.success) {
      io.to(cleanRoomId).emit('room:state-update', res.roomState);
      if (res.finishMsg) io.to(cleanRoomId).emit('chat:message', res.finishMsg);
    }
  });

  // 7. Grounded AI Study Moderator
  socket.on('ai:ask', async ({ roomId, userQuery, userName }, callback) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const res = await roomManager.askAiModerator(cleanRoomId, userQuery, userName);
    if (typeof callback === 'function') callback(res);
    if (res.success) {
      io.to(cleanRoomId).emit('chat:message', res.aiMsg);
      io.to(cleanRoomId).emit('room:state-update', res.roomState);
    }
  });

  // 8. AI Group Challenge
  socket.on('ai:challenge-start', async ({ roomId }, callback) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const res = await roomManager.startAiChallenge(cleanRoomId, socket.id);
    if (typeof callback === 'function') callback(res);
    if (res.success) {
      io.to(cleanRoomId).emit('room:state-update', res.roomState);
      if (res.challengeMsg) io.to(cleanRoomId).emit('chat:message', res.challengeMsg);
    }
  });

  socket.on('ai:challenge-analyze', ({ roomId }, callback) => {
    const cleanRoomId = (roomId || '').trim().toUpperCase();
    const res = roomManager.revealAiChallengeAnalysis(cleanRoomId, socket.id);
    if (typeof callback === 'function') callback(res);
    if (res.success) {
      io.to(cleanRoomId).emit('room:state-update', res.roomState);
      if (res.analysisMsg) io.to(cleanRoomId).emit('chat:message', res.analysisMsg);
    }
  });
});

httpServer.listen(PORT, () => {
  console.log(`[StudyFlow Backend] Server running with Socket.IO on http://localhost:${PORT}`);
});

